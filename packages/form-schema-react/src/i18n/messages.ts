export const rendererMessages: Readonly<Record<'en' | 'de', RendererMessages>> = { en, de };

/** Picks the catalog for a BCP 47 tag (`de-DE` → `de`, unknown → `en`) and applies overrides. */
export function resolveMessages(
    locale: string | undefined,
    overrides: Partial<RendererMessages> = {},
): RendererMessages {
    const language = (locale ?? 'en').toLowerCase().split('-')[0];
    const base = language === 'de' ? de : en;
    return { ...base, ...overrides };
}

/** Replaces `{name}` placeholders with the given values. */
export function interpolate(
    template: string,
    params: Readonly<Record<string, string | number>> = {},
): string {
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        Object.hasOwn(params, name) ? String(params[name]) : match,
    );
}
