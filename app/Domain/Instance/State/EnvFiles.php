<?php

declare(strict_types=1);

namespace App\Domain\Instance\State;

use App\Domain\Instance\InstanceException;
use App\Domain\Instance\Output\ExitCode;
use SensitiveParameter;

/**
 * Per-service env files (KTD7): `env/<service>.env`, mode 0600 in a 0700 directory, each holding only the keys
 * its service needs. They are the only place secrets live. The format is Compose's env_file syntax: values are
 * single-quoted (literal, no interpolation); a value containing a single quote, or ending in a backslash (Compose reads
 * `\'` inside single quotes as an escaped quote, so `A='x\'` runs on into the next line), is double-quoted with `\\`,
 * `\"` and `\$` escaped (verified against Compose 5.0.2, LEARNINGS 79). Lines end with LF (CRLF is read too): any
 * other byte, the 0x85 of UTF-8 Å, х or ą and other control characters included, is part of the value (M11 gate).
 */
final readonly class EnvFiles
{
    private const string SERVICE = '/^[a-z0-9][a-z0-9_-]{0,62}$/D';

    private const string KEY = '/^[A-Z_][A-Z0-9_]*$/D';

    /** Keys whose values are secrets; the console base scrubs these values from every output (R50). */
    private const string SECRET_KEY = '/(PASSWORD|PASSPHRASE|SECRET|TOKEN|KEY|AUTH)/';

    private const string HEADER = "# Generated by fieldset from the instance state. Do not edit; use `fieldset config set`.\n";

    public function __construct(private InstanceDirectory $directory) {}

    /** @param  array<string, string>  $values */
    public function write(string $service, #[SensitiveParameter] array $values): void
    {
        $this->directory->ensureDirectory(InstanceDirectory::ENV_DIR, 0700);
        $this->directory->write($this->relativePath($service), self::encode($values), 0600);
    }

    /** @return array<string, string> */
    public function read(string $service): array
    {
        $contents = $this->directory->read($this->relativePath($service));

        return $contents === null ? [] : self::decode($contents);
    }

    public function exists(string $service): bool
    {
        return $this->directory->exists($this->relativePath($service));
    }

    public function remove(string $service): void
    {
        $this->directory->files()->delete($this->relativePath($service));
    }

    /** Absolute path, for the compose file's `env_file`. */
    public function path(string $service): string
    {
        return $this->directory->path($this->relativePath($service));
    }

    /** @return list<string> services that have an env file */
    public function services(): array
    {
        $names = array_filter($this->directory->files()->list(InstanceDirectory::ENV_DIR), static fn (string $name): bool => str_ends_with($name, '.env'));

        return array_values(array_map(static fn (string $name): string => substr($name, 0, -4), $names));
    }

    /** @return list<string> values of secret-looking keys in all env files, for the output redactor */
    public function secretValues(): array
    {
        $values = [];
        foreach ($this->services() as $service) {
            foreach ($this->read($service) as $key => $value) {
                if (preg_match(self::SECRET_KEY, $key) === 1 && $value !== '') {
                    $values[] = $value;
                    // A list of keys (APP_PREVIOUS_KEYS): each one alone is a secret too.
                    array_push($values, ...(str_ends_with($key, '_KEYS') ? array_filter(array_map(trim(...), explode(',', $value))) : []));
                }
            }
        }

        return $values;
    }

    public function relativePath(string $service): string
    {
        if (preg_match(self::SERVICE, $service) !== 1) {
            throw new InstanceException("Invalid service name [{$service}].", ExitCode::InvalidInput, 'invalid_service');
        }

        return InstanceDirectory::ENV_DIR.'/'.$service.'.env';
    }

    /** @param  array<string, string>  $values */
    public static function encode(#[SensitiveParameter] array $values): string
    {
        $lines = [];
        foreach ($values as $key => $value) {
            if (preg_match(self::KEY, $key) !== 1) {
                throw new InstanceException("Invalid environment variable name [{$key}].", ExitCode::InvalidInput, 'invalid_env_key');
            }
            if (preg_match('/[\r\n\0]/', $value) === 1) {
                throw new InstanceException("The value of {$key} contains a line break or NUL byte.", ExitCode::InvalidInput, 'invalid_env_value');
            }
            $lines[] = $key.'='.(str_contains($value, "'") || str_ends_with($value, '\\')
                ? '"'.str_replace(['\\', '"', '$'], ['\\\\', '\\"', '\\$'], $value).'"'
                : "'".$value."'");
        }

        return self::HEADER.implode("\n", $lines).($lines === [] ? '' : "\n");
    }

    /** @return array<string, string> */
    public static function decode(#[SensitiveParameter] string $contents): array
    {
        $values = [];
        foreach (preg_split('/\r?\n/', $contents) ?: [] as $line) {
            if (trim($line) === '' || str_starts_with(ltrim($line), '#') || ! str_contains($line, '=')) {
                continue;
            }
            [$key, $raw] = explode('=', $line, 2);
            $values[trim($key)] = self::unquote($raw);
        }

        return $values;
    }

    private static function unquote(string $raw): string
    {
        if (strlen($raw) >= 2 && $raw[0] === "'" && str_ends_with($raw, "'")) {
            return substr($raw, 1, -1);
        }
        if (strlen($raw) >= 2 && $raw[0] === '"' && str_ends_with($raw, '"')) {
            return (string) preg_replace('/\\\\(.)/s', '$1', substr($raw, 1, -1));
        }

        return trim($raw);
    }
}
