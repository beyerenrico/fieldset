<?php

declare(strict_types=1);

namespace App\Domain\Instance\Compose;

use App\Domain\Instance\State\EnvFiles;
use App\Domain\Instance\State\InstanceDirectory;
use SensitiveParameter;

/**
 * A rendered compose project: the compose document, which holds no secret, and one environment per service,
 * which goes to its 0600 env file. The file is written as JSON, which is valid YAML: symfony/yaml is not a
 * dependency, and emitting a structure through json_encode leaves no room for injection (ADR 0069).
 */
final readonly class RenderedProject
{
    public const string HEADER = "# Generated by fsa from the instance state (state.json). Do not edit: use `fsa config set`.\n"
        ."# JSON is valid YAML; secrets live in env/<service>.env, never here.\n";

    /**
     * @param  array<string, mixed>  $document
     * @param  array<string, array<string, string>>  $environments  service => env file contents
     */
    public function __construct(
        public string $project,
        public array $document,
        #[SensitiveParameter] public array $environments,
    ) {}

    public function yaml(): string
    {
        return self::HEADER.json_encode($this->document, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n";
    }

    /** @return list<string> service names, in render order (every service has exactly one environment) */
    public function services(): array
    {
        return array_keys($this->environments);
    }

    /** @return array<string, mixed> */
    public function service(string $name): array
    {
        return $this->document['services'][$name] ?? [];
    }

    /** @return array<string, int> service => MiB */
    public function memoryLimits(): array
    {
        return array_map(static fn (array $service): int => (int) $service['mem_limit'], $this->document['services']);
    }

    /**
     * Env files first (the compose file references them), then the compose file; env files of services that are
     * no longer rendered are removed, so no secret outlives its service.
     */
    public function writeTo(InstanceDirectory $directory): void
    {
        $env = new EnvFiles($directory);
        foreach ($this->environments as $service => $values) {
            $env->write($service, $values);
        }
        foreach (array_diff($env->services(), array_keys($this->environments)) as $stale) {
            $env->remove($stale);
        }
        $directory->write(InstanceDirectory::COMPOSE_FILE, $this->yaml(), 0600);
    }
}
