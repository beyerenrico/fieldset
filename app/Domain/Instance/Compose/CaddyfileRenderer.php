<?php

declare(strict_types=1);

namespace App\Domain\Instance\Compose;

use App\Domain\Instance\Compose\Services\AppRoles;
use App\Domain\Instance\Compose\Services\MailpitService;
use App\Domain\Instance\InstanceException;
use App\Domain\Instance\Output\ExitCode;
use App\Domain\Instance\Runtime\CatcherRoute;
use App\Domain\Instance\Runtime\PhoneTrustRoute;

/**
 * The edge's Caddyfile for domain mode (plan KTD10, R16, R66; ADR 0075), built as a tree and serialized, never
 * concatenated from input. Every value from the state is a quoted token: control characters, double quotes,
 * backslashes, backticks and braces are refused, so a value can neither end its token or line nor reach Caddy's
 * `{$ENV}` substitution or `{placeholder}` expansion. Code literals (directives, matchers, upstreams) are checked
 * against a plain-token pattern. The catcher's Basic credential is never in the file: the edge reads it from its env
 * file at runtime (`{env.…}`).
 *
 * What it renders:
 * - global: admin API and config autosave off; ACME directory (Let's Encrypt production unless configured), optional
 *   contact and custom root for the directory's HTTPS (Pebble in the journeys);
 * - the domain site: automatic HTTPS with Caddy's HTTP→HTTPS redirect; everything proxied to the app unchanged but
 *   for a client's X-Forwarded-Port, so the app's own headers (CSP, HSTS, preview CORS) pass through; `/_fsa/*` (the
 *   auth endpoint) answers 404 from outside; in capture mode `/_mail/` goes through `forward_auth` to the app (an
 *   operator's /platform session with MFA, R66) and then to Mailpit with the edge-injected Basic credential and
 *   without the browser's cookies, with framing limited to the same origin (Mailpit's Raw tab frames itself),
 *   nosniff, no-store, and a stream timeout that ends an open live-update socket after the session is gone
 *   (LEARNINGS 103);
 * - a loopback-only health site for the container healthcheck.
 *
 * Local-CA mode (R19, ADR 0082) renders another shape from a LocalCaSite: no ACME; Caddy's internal CA (named, its
 * root never installed into a trust store of the container) issues the certificate for the LAN address, `default_sni`
 * picks it for clients that connect by IP without SNI, and port 80 forwards only the phone trust page and the root
 * certificate to the app (PhoneTrustRoute) while everything else gets 308 to HTTPS; Caddy's own redirects are off, so
 * that rule holds for every Host on port 80.
 *
 * No access log is configured (Caddy's default): sign-in link tokens travel in the URL fragment anyway, and the app
 * keeps its own logs.
 */
final readonly class CaddyfileRenderer
{
    /** Where the edge mounts the instance's `edge/` directory (read-only). */
    public const string CONTAINER_DIR = '/etc/caddy';

    public const string FILE = 'Caddyfile';

    /** The custom ACME CA root (`--acme-ca-root-file`), next to the Caddyfile. */
    public const string ACME_ROOT_FILE = 'acme-ca-root.pem';

    /** The edge's env variable with `Basic <base64(fsa:catcher password)>` towards Mailpit. */
    public const string AUTHORIZATION_ENV = 'FSA_CATCHER_AUTHORIZATION';

    public const int HEALTH_PORT = 8081;

    public const string HEALTH_PATH = '/healthz';

    /** An open catcher live-update socket ends after this; Mailpit reconnects through forward_auth. */
    public const string STREAM_TIMEOUT = '5m';

    public const string HEADER = '# Generated by fsa from the instance state (state.json). Do not edit: use `fsa config set`.';

    /**
     * Caddy sets X-Forwarded-For, -Proto and -Host itself (it trusts no incoming ones) but passes a client's
     * X-Forwarded-Port on, which the app trusts from the edge: it is removed towards the app (ADR 0079).
     */
    private const array STRIP_FORWARDED_PORT = [['header_up', '-X-Forwarded-Port']];

    private const string LITERAL = '/^[A-Za-z0-9_\-\/*.:@+]+$/D';

    private const string UNSAFE = '/[\x00-\x1F\x7F"\\\\`{}]/';

    private const string ENV_NAME = '/^[A-Z][A-Z0-9_]*$/D';

    public function render(EdgeSite|LocalCaSite $site): string
    {
        $tree = $site instanceof LocalCaSite ? $this->localCa($site) : [
            [[], $this->globalOptions($site)],
            [[['value' => $site->domain]], $this->domainSite($site)],
        ];
        $tree[] = [['http://:'.self::HEALTH_PORT], [[['bind', '127.0.0.1']], [['respond', self::HEALTH_PATH, ['value' => 'ok'], '200']]]];
        $blocks = array_map(fn (array $node): string => $this->node($node, 0), $tree);

        return self::HEADER."\n".implode("\n\n", $blocks)."\n";
    }

    /** A double-quoted Caddyfile token; refuses what could end the token or reach substitution or placeholders. */
    public static function quote(string $value): string
    {
        if (preg_match(self::UNSAFE, $value) === 1 || preg_match('//u', $value) !== 1) {
            throw new InstanceException('A Caddyfile value contains a quote, backslash, brace or control character.', ExitCode::InternalError, 'unsafe_caddyfile');
        }

        return '"'.$value.'"';
    }

    /** @return list<array<int, mixed>> */
    private function globalOptions(EdgeSite $site): array
    {
        return array_values(array_filter([
            [['admin', 'off']],
            [['persist_config', 'off']],
            $site->acmeEmail === null ? null : [['email', ['value' => $site->acmeEmail]]],
            [['acme_ca', ['value' => $site->acmeCa]]],
            $site->acmeCaRoot ? [['acme_ca_root', ['value' => self::CONTAINER_DIR.'/'.self::ACME_ROOT_FILE]]] : null,
        ]));
    }

    /** @return list<array<int, mixed>> */
    private function domainSite(EdgeSite $site): array
    {
        $app = AppRoles::APP.':'.AppRoles::PORT;

        return [
            [['handle', CatcherRoute::INTERNAL_PREFIX.'*'], [[['respond', '404']]]],
            ...($site->catcher ? $this->catcher($app) : []),
            [['handle'], [[['reverse_proxy', $app], [self::STRIP_FORWARDED_PORT]]]],
        ];
    }

    /** @return list<array<int, mixed>> local-CA mode: global options, the HTTPS site for the LAN address, port 80 */
    private function localCa(LocalCaSite $site): array
    {
        $address = $site->address;
        if (filter_var($address, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) === false) {
            throw new InstanceException("The local-CA address [{$address}] is not an IPv4 address.", ExitCode::InternalError, 'unsafe_caddyfile');
        }
        $app = AppRoles::APP.':'.AppRoles::PORT;

        return [
            [[], [
                [['admin', 'off']],
                [['persist_config', 'off']],
                [['skip_install_trust']],
                [['auto_https', 'disable_redirects']],
                [['default_sni', ['value' => $address]]],
                [['pki'], [[['ca', 'local'], [[['name', ['value' => LocalCaSite::CA_NAME]]]]]]],
            ]],
            [[['value' => $site->httpsUrl()]], [
                [['tls', 'internal']],
                [['handle', CatcherRoute::INTERNAL_PREFIX.'*'], [[['respond', '404']]]],
                [['handle'], [[['reverse_proxy', $app], [self::STRIP_FORWARDED_PORT]]]],
            ]],
            [[['value' => 'http://']], [
                [['@phone_trust', 'path', PhoneTrustRoute::PATH, PhoneTrustRoute::PATH.'/*']],
                [['handle', '@phone_trust'], [[['reverse_proxy', $app], [self::STRIP_FORWARDED_PORT]]]],
                [['handle'], [[['redir', ['https_to' => $address], '308']]]],
            ]],
        ];
    }

    /** @return list<array<int, mixed>> the catcher UI behind forward_auth (R66, LEARNINGS 103) */
    private function catcher(string $app): array
    {
        $mail = CatcherRoute::MAIL_PATH;

        return [
            [['redir', rtrim($mail, '/'), $mail, '308']],
            [['handle', $mail.'*'], [
                [['forward_auth', $app], [
                    [['uri', ['value' => CatcherRoute::AUTH_PATH]]],
                    // The auth subrequest must not carry the browser's credentials for Mailpit or try to upgrade.
                    [['header_up', '-Authorization']],
                    [['header_up', '-Upgrade']],
                    [['header_up', '-Connection']],
                    self::STRIP_FORWARDED_PORT,
                ]],
                [['header'], [
                    [['defer']],
                    [['X-Frame-Options', ['value' => 'SAMEORIGIN']]],
                    [['X-Content-Type-Options', ['value' => 'nosniff']]],
                    // Added to Mailpit's own policy (nonce scripts), not replacing it: both are enforced.
                    [['+Content-Security-Policy', ['value' => "frame-ancestors 'self'"]]],
                    [['Referrer-Policy', ['value' => 'no-referrer']]],
                    [['Cache-Control', ['value' => 'no-store']]],
                ]],
                [['reverse_proxy', MailpitService::NAME.':'.MailpitService::UI_PORT], [
                    // forward_auth has seen the operator's session; Mailpit gets neither it nor the XSRF token.
                    [['header_up', '-Cookie']],
                    [['header_up', '-X-XSRF-TOKEN']],
                    [['header_up', 'Authorization', ['env' => self::AUTHORIZATION_ENV]]],
                    [['stream_timeout', self::STREAM_TIMEOUT]],
                ]],
            ]],
        ];
    }

    /** @param  array<int, mixed>  $node  [tokens, children?] */
    private function node(array $node, int $depth): string
    {
        $indent = str_repeat("\t", $depth);
        /** @var list<string|array{value?: string, env?: string, https_to?: string}> $tokens */
        $tokens = $node[0];
        $head = implode(' ', array_map($this->token(...), $tokens));
        if (! isset($node[1])) {
            return $indent.$head;
        }
        $line = $indent.($head === '' ? '{' : $head.' {'); // no tokens: the global options block
        /** @var list<array<int, mixed>> $children */
        $children = $node[1];
        $inner = array_map(fn (array $child): string => $this->node($child, $depth + 1), $children);

        return $line."\n".implode("\n", $inner)."\n".$indent.'}';
    }

    /** @param  string|array{value?: string, env?: string, https_to?: string}  $token */
    private function token(string|array $token): string
    {
        if (is_array($token) && isset($token['https_to'])) {
            // The redirect target keeps the request URI: the only placeholder besides the env one, after an IPv4 address.
            if (filter_var($token['https_to'], FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) === false) {
                throw new InstanceException('The redirect target is not an IPv4 address.', ExitCode::InternalError, 'unsafe_caddyfile');
            }

            return '"https://'.$token['https_to'].'{uri}"';
        }
        if (is_array($token) && isset($token['env'])) {
            if (preg_match(self::ENV_NAME, $token['env']) !== 1) {
                throw new InstanceException("Invalid environment placeholder [{$token['env']}].", ExitCode::InternalError, 'unsafe_caddyfile');
            }

            return '"{env.'.$token['env'].'}"';
        }
        if (is_array($token)) {
            return self::quote($token['value'] ?? '');
        }
        if (preg_match(self::LITERAL, $token) !== 1) {
            throw new InstanceException("Invalid Caddyfile literal [{$token}].", ExitCode::InternalError, 'unsafe_caddyfile');
        }

        return $token;
    }
}
