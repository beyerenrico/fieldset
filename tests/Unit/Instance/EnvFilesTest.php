<?php

declare(strict_types=1);

use App\Domain\Instance\InstanceException;
use App\Domain\Instance\State\EnvFiles;
use Tests\Support\Instance\TemporaryInstance;

afterEach(fn () => TemporaryInstance::cleanup());

it('writes one 0600 env file per service in a 0700 directory', function (): void {
    $directory = TemporaryInstance::directory();
    $env = new EnvFiles($directory);

    $env->write('app', ['APP_KEY' => 'base64:abc+/=', 'DB_PASSWORD' => 's3cret']);
    $env->write('gotenberg', ['CHROMIUM_MAX_CONCURRENCY' => '1']);

    expect(fileperms($env->path('app')) & 0777)->toBe(0600)
        ->and(fileperms($directory->path('env')) & 0777)->toBe(0700)
        ->and($env->path('app'))->toBe($directory->root.'/env/app.env')
        ->and($env->services())->toBe(['app', 'gotenberg'])
        ->and($env->read('app'))->toBe(['APP_KEY' => 'base64:abc+/=', 'DB_PASSWORD' => 's3cret'])
        ->and($env->read('gotenberg'))->not->toHaveKey('APP_KEY')
        ->and($env->exists('mailpit'))->toBeFalse()
        ->and($env->read('mailpit'))->toBe([]);

    $env->remove('gotenberg');
    expect($env->services())->toBe(['app']);
});

it('quotes values so Compose takes them literally', function (): void {
    $encoded = EnvFiles::encode([
        'PLAIN' => 'a $HOME ${X} \\n "dq"',
        'QUOTE' => "it's \$5 \\ \"x\"",
        'EMPTY' => '',
    ]);

    expect($encoded)->toContain("PLAIN='a \$HOME \${X} \\n \"dq\"'\n")
        ->toContain('QUOTE="it\'s \\$5 \\\\ \\"x\\""'."\n")
        ->toContain("EMPTY=''\n")
        ->toStartWith('# Generated by fsa');
});

it('decodes what it encodes, for every awkward value', function (string $value): void {
    expect(EnvFiles::decode(EnvFiles::encode(['V' => $value])))->toBe(['V' => $value]);
})->with([
    'dollar' => ['$HOME ${PATH} $$'],
    'single quote' => ["it's"],
    'mixed' => ["a\\\$b'c\"d"],
    'hash' => ['p#ss word'],
    'backslash end' => ["x'\\"],
    'unicode' => ["pässwört'"],
]);

it('reads unquoted values written by hand', function (): void {
    expect(EnvFiles::decode("# comment\n\nA=plain\nnot a pair\n B = spaced \n"))->toBe(['A' => 'plain', 'B' => 'spaced']);
});

it('rejects invalid service names, keys and multi-line values', function (Closure $call, string $message): void {
    $env = new EnvFiles(TemporaryInstance::directory());

    expect(fn () => $call($env))->toThrow(InstanceException::class, $message);
})->with([
    'service' => [fn (EnvFiles $env) => $env->write('../app', []), 'Invalid service name'],
    'key' => [fn (EnvFiles $env) => $env->write('app', ['lower' => 'x']), 'Invalid environment variable name'],
    'newline' => [fn (EnvFiles $env) => $env->write('app', ['A' => "x\ny"]), 'line break'],
]);

it('lists the values of secret-looking keys across services', function (): void {
    $env = new EnvFiles(TemporaryInstance::directory());
    $env->write('app', ['APP_KEY' => 'base64:k', 'DB_PASSWORD' => 'p1', 'DB_HOST' => 'postgres', 'MAIL_PORT' => '1025']);
    $env->write('mailpit', ['MP_UI_AUTH' => 'admin:pw', 'MP_MAX_MESSAGES' => '500']);
    $env->write('backup', ['BACKUP_HMAC_KEY' => 'h', 'AGE_RECIPIENT' => 'age1abc', 'SMTP_TOKEN' => 't', 'S3_SECRET' => 's']);

    expect($env->secretValues())->toBe(['base64:k', 'p1', 'h', 't', 's', 'admin:pw']);
});
